import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

import {
  readLocalHooksManifest,
  fetchHooksManifest,
  resolveHooks,
  installHooks,
  removeHooks,
} from "../src/hooks.mjs";

const SAMPLE = {
  hooks: {
    session_start: [{ skill: "team-boot", timeout: 60 }],
  },
};

describe("Hooks: manifest discovery (canonical)", () => {
  it("reads local .hooks.json", () => {
    const dir = mkdtempSync(join(tmpdir(), "adlc-hooks-"));
    try {
      writeFileSync(join(dir, ".hooks.json"), JSON.stringify(SAMPLE), "utf-8");
      const manifest = readLocalHooksManifest(dir);
      assert.deepEqual(Object.keys(manifest.hooks), ["session_start"]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("falls back to deprecated .events.json", async () => {
    const dir = mkdtempSync(join(tmpdir(), "adlc-hooks-fallback-"));
    try {
      writeFileSync(
        join(dir, ".events.json"),
        JSON.stringify({ events: { session_start: [{ skill: "team-boot" }] } }),
        "utf-8",
      );
      const manifest = readLocalHooksManifest(dir);
      assert.ok(manifest, "fallback manifest resolved");
      const resolved = resolveHooks(manifest, { canonical_to_native: { session_start: "SessionStart" } });
      assert.deepEqual(Object.keys(resolved), ["session_start"]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("prefers .hooks.json over .events.json", () => {
    const dir = mkdtempSync(join(tmpdir(), "adlc-hooks-prefer-"));
    try {
      writeFileSync(join(dir, ".hooks.json"), JSON.stringify(SAMPLE), "utf-8");
      writeFileSync(
        join(dir, ".events.json"),
        JSON.stringify({ events: { user_prompt_submit: [{ skill: "other" }] } }),
        "utf-8",
      );
      const manifest = readLocalHooksManifest(dir);
      assert.deepEqual(Object.keys(manifest.hooks), ["session_start"]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("fetchHooksManifest resolves bare local dir with .hooks.json", async () => {
    const parent = mkdtempSync(join(tmpdir(), "adlc-hooks-bare-"));
    const origCwd = process.cwd();
    try {
      process.chdir(parent);
      const dirName = "skills-src-hooks";
      const { mkdirSync } = await import("node:fs");
      mkdirSync(join(parent, dirName), { recursive: true });
      writeFileSync(join(parent, dirName, ".hooks.json"), JSON.stringify(SAMPLE), "utf-8");
      const manifest = await fetchHooksManifest(dirName);
      assert.ok(manifest, "manifest resolved");
    } finally {
      process.chdir(origCwd);
      rmSync(parent, { recursive: true, force: true });
    }
  });

  it("deprecated events aliases still work", async () => {
    const { readLocalEventsManifest, fetchEventsManifest, resolveEvents } = await import("../src/events.mjs");
    const dir = mkdtempSync(join(tmpdir(), "adlc-events-alias-"));
    try {
      writeFileSync(join(dir, ".hooks.json"), JSON.stringify(SAMPLE), "utf-8");
      const manifest = readLocalEventsManifest(dir);
      assert.ok(manifest, "alias reads canonical file");
      assert.equal(typeof fetchEventsManifest, "function");
      assert.equal(typeof resolveEvents, "function");
      assert.equal(typeof installHooks, "function");
      assert.equal(typeof removeHooks, "function");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("install removes legacy opencode plugin path carrying our marker (F1)", async () => {
    const { mkdtempSync: mk, mkdirSync: mkd, writeFileSync: wfs, existsSync: ex, readFileSync: rfs } = await import("node:fs");
    const { getHookAgentConfig } = await import("../src/registry.mjs");
    const dir = mk(join(tmpdir(), "adlc-f1-"));
    try {
      const legacy = join(dir, ".opencode", "plugins", "adlc-skills-events.ts");
      mkd(join(dir, ".opencode", "plugins"), { recursive: true });
      wfs(legacy, "// generated by adlc-cli; source: adlc-events — do not edit\n", "utf-8");
      const resolved = resolveHooks(SAMPLE, getHookAgentConfig("opencode"));
      installHooks("opencode", dir, resolved, ".agents/skills");
      assert.equal(ex(legacy), false, "legacy plugin path removed on install");
      assert.ok(ex(join(dir, ".opencode", "plugins", "adlc-skills-hooks.ts")), "canonical plugin written");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("install keeps legacy opencode plugin without our marker (F1)", async () => {
    const { mkdtempSync: mk, mkdirSync: mkd, writeFileSync: wfs, existsSync: ex, readFileSync: rfs } = await import("node:fs");
    const { getHookAgentConfig } = await import("../src/registry.mjs");
    const dir = mk(join(tmpdir(), "adlc-f1-keep-"));
    try {
      const legacy = join(dir, ".opencode", "plugins", "adlc-skills-events.ts");
      mkd(join(dir, ".opencode", "plugins"), { recursive: true });
      wfs(legacy, "// user-crafted plugin, hands off\n", "utf-8");
      const resolved = resolveHooks(SAMPLE, getHookAgentConfig("opencode"));
      installHooks("opencode", dir, resolved, ".agents/skills");
      assert.equal(ex(legacy), true, "user file preserved");
      assert.equal(rfs(legacy, "utf-8"), "// user-crafted plugin, hands off\n");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("remove deletes legacy opencode plugin path carrying our marker (F1)", async () => {
    const { mkdtempSync: mk, mkdirSync: mkd, writeFileSync: wfs, existsSync: ex } = await import("node:fs");
    const dir = mk(join(tmpdir(), "adlc-f1-rm-"));
    try {
      const legacy = join(dir, ".opencode", "plugins", "adlc-skills-events.ts");
      mkd(join(dir, ".opencode", "plugins"), { recursive: true });
      wfs(legacy, "// generated by adlc-cli; source: adlc-hooks — do not edit\n", "utf-8");
      const result = removeHooks("opencode", dir);
      assert.equal(ex(legacy), false, "legacy plugin path removed on teardown");
      assert.ok(result === null || result.action !== "manual", "no manual action needed");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("removeToml legacy header-only file is deleted (N5)", async () => {
    const { mkdtempSync: mk, mkdirSync: mkd, writeFileSync: wfs, existsSync: ex } = await import("node:fs");
    const dir = mk(join(tmpdir(), "adlc-n5-"));
    try {
      const { join: jj } = await import("node:path");
      const codexDir = jj(dir, ".codex");
      mkd(codexDir, { recursive: true });
      // Header-only legacy file: after stripping (no blocks), only legacy header remains → delete.
      wfs(jj(codexDir, "config.toml"), "# generated by adlc-cli; source: adlc-events — do not edit\n", "utf-8");
      const result = removeHooks("codex", dir);
      assert.equal(ex(jj(codexDir, "config.toml")), false, "legacy header-only toml removed");
      assert.equal(result && result.action, "deleted");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
